MARKDOWN = [
    (r"\*\*", "粗體符號 **（Threads 不支援，會原樣顯示）"),
    (r"^#{1,6}\s", "開頭的 # 標題符號（Threads 會當成話題標籤）"),
    (r"^\s*[-*]\s", "Markdown 清單符號（建議直接用 1. 2. 或 emoji）"),
    (r"\[[^\]]+\]\([^)]+\)", "Markdown 連結寫法（Threads 直接貼網址就好）"),
]


def items():
    if not POSTS.exists():
        return []
    return sorted((d for d in POSTS.iterdir()
                   if not d.name.startswith(".") and (d.is_dir() or d.suffix.lower() == ".txt")),
                  key=lambda d: d.name)


def check(d):
    bad, warn = [], []
    if d.is_file():
        text, imgs, others = d.read_text("utf-8").strip(), [], []
    else:
        files = [f for f in sorted(d.iterdir()) if f.is_file() and not f.name.startswith(".")]
        txts = [f for f in files if f.suffix.lower() == ".txt"]
        imgs = [f for f in files if f.suffix.lower() in IMG_OK]
        others = [f for f in files if f not in txts and f not in imgs]
        text = "\n\n".join(t.read_text("utf-8").strip() for t in txts)

    n = len(text)
    if others:
        bad.append(f"有不支援的檔案：{', '.join(o.name for o in others)}（只收 jpg/png，iPhone 的 HEIC 要先轉檔）")
    if not text and not imgs:
        bad.append("是空的")
    if n > 500:
        import math
        warn.append(f"文案 {n} 字，會自動切成 {math.ceil(n / 170)} 篇左右串成長文（第一篇帶圖）")
    if len(imgs) > 20:
        bad.append(f"{len(imgs)} 張圖，超過上限 20 張")
    for img in imgs:
        mb = img.stat().st_size / 1048576
        if mb > 8:
            bad.append(f"{img.name} 有 {mb:.1f}MB，超過單張 8MB 上限")
        elif img.stat().st_size == 0:
            bad.append(f"{img.name} 是空檔案")

    for pattern, why in MARKDOWN:
        if re.search(pattern, text, re.M):
            warn.append(why)
    tags = re.findall(r"#[^\s#]+", text)
    if len(tags) > 1:
        warn.append(f"有 {len(tags)} 個話題標籤（{' '.join(tags)}），Threads 只認第一個")
    simp = sorted({c for c in text if c in SIMPLIFIED})
    if simp:
        warn.append(f"可能有簡體字：{' '.join(simp[:15])}{' …' if len(simp) > 15 else ''}")
    if d.is_dir() and imgs and not text:
        warn.append("有圖但沒有文案，確定是純圖貼文嗎？")

    kind = "純文字" if not imgs else ("單圖" if len(imgs) == 1 else f"輪播 {len(imgs)} 張")
    return n, kind, bad, warn


def main():
    rows = items()
    if not rows:
        print("posts 裡沒有東西，這幾天不會發任何貼文。")
        return 0
    print(f"共 {len(rows)} 篇待發\n" + "=" * 40)
    nbad = 0
    for d in rows:
        n, kind, bad, warn = check(d)
        mark = "❌" if bad else ("⚠️ " if warn else "✅")
        print(f"\n{mark} {d.name}　{kind}　{n} 字")
        for b in bad:
            print(f"   ❌ {b}")
        for w in warn:
            print(f"   ⚠️  {w}")
        nbad += bool(bad)
    print("\n" + "=" * 40)
    if nbad:
        print(f"有 {nbad} 篇發不出去（❌），改好再同步。前面標 ⚠️ 的只是提醒，不影響發布。")
    else:
        print("全部都能正常發出去。標 ⚠️ 的只是提醒，不影響發布。")
    return 1 if nbad else 0


if __name__ == "__main__":
    sys.exit(main())
